// One-off generator for tests/fixtures/conflict/mined-block.json. It mines one
// testnet-minimum-difficulty header after the real checkpoint containing the
// deterministic conflict fixture's issuance and branch A, so conflict and door
// tests can run real Merkle, linkage and proof-of-work checks with no stubs.
// Run: node --experimental-strip-types scripts/fixtures/mine-conflict-block.ts
import { Worker, isMainThread, parentPort, workerData } from 'node:worker_threads'
import { createHash } from 'node:crypto'
import { availableParallelism } from 'node:os'
import { mkdirSync, writeFileSync } from 'node:fs'

const sha256d = (b: Buffer) => createHash('sha256').update(createHash('sha256').update(b).digest()).digest()
const BITS = 0x1d00ffff // Testnet's minimum difficulty, the easiest target validation accepts.

function mine({ prefix, start, step }: { prefix: Buffer; start: number; step: number }): void {
  const header = Buffer.alloc(80)
  Buffer.from(prefix).copy(header, 0)
  for (let time = start; ; time += step) {
    header.writeUInt32LE(time, 68)
    for (let nonce = 0; nonce <= 0xffffffff; nonce++) {
      header.writeUInt32LE(nonce, 76)
      const hash = sha256d(header)
      // Target 0x00000000ffff…: the four most significant bytes (stored last) are zero, then compare.
      if (hash[31] === 0 && hash[30] === 0 && hash[29] === 0 && hash[28] === 0 && (hash[27] < 0xff || hash[26] < 0xff)) {
        parentPort!.postMessage(header.toString('hex'))
        return
      }
    }
  }
}
if (!isMainThread) mine(workerData)
else {
  const root = new URL('../../', import.meta.url)
  const { conflictFixture } = await import(new URL('tests/helpers/conflict-fixture.ts', root).href)
  const { makeSnapshot, parseProviderHeader } = await import(new URL('src/headers/validate.ts', root).href)
  const checkpoint = (await import(new URL('tests/fixtures/headers/woc-1762324.json', root).href, { with: { type: 'json' } })).default
  const { MerklePath } = await import(new URL('node_modules/@bsv/sdk/dist/esm/mod.js', root).href)
  const f = await conflictFixture(),
    a = await f.branch(f.a, 1)
  const { Transaction } = await import(new URL('node_modules/@bsv/sdk/dist/esm/mod.js', root).href)
  const issuanceTxid: string = f.issuance.id('hex'),
    winnerTxid: string = Transaction.fromAtomicBEEF(Buffer.from(a.pkg.atomicBeefBase64, 'base64')).id('hex')
  const rev = (hex: string) => Buffer.from(hex, 'hex').reverse()
  const parent = (l: string, r: string) =>
    sha256d(Buffer.concat([rev(l), rev(r)]))
      .reverse()
      .toString('hex')
  const filler = '11'.repeat(32),
    h01 = parent(filler, issuanceTxid),
    h23 = parent(winnerTxid, winnerTxid),
    merkleRoot = parent(h01, h23)
  const height = checkpoint.height + 1
  const issuancePath = new MerklePath(height, [
    [
      { offset: 0, hash: filler },
      { offset: 1, hash: issuanceTxid, txid: true },
    ],
    [{ offset: 1, hash: h23 }],
  ])
  const winnerPath = new MerklePath(height, [
    [
      { offset: 2, hash: winnerTxid, txid: true },
      { offset: 3, duplicate: true },
    ],
    [{ offset: 0, hash: h01 }],
  ])
  if (issuancePath.computeRoot(issuanceTxid) !== merkleRoot || winnerPath.computeRoot(winnerTxid) !== merkleRoot)
    throw Error('Merkle paths do not reach the computed root')
  const prefix = Buffer.alloc(80)
  prefix.writeUInt32LE(0x20000000, 0)
  rev(checkpoint.hash).copy(prefix, 4)
  rev(merkleRoot).copy(prefix, 36)
  prefix.writeUInt32LE(BITS, 72)
  const workers = availableParallelism(),
    base = checkpoint.time + 1200,
    started = Date.now()
  console.log(`Mining height ${height} on ${workers} workers (about 4.3 billion hashes expected)…`)
  const hex: string = await new Promise((resolve, reject) => {
    const pool = Array.from(
      { length: workers },
      (_, i) =>
        new Worker(new URL(import.meta.url), { workerData: { prefix, start: base + i, step: workers }, execArgv: process.execArgv }),
    )
    for (const w of pool) {
      w.on('message', (found: string) => {
        for (const other of pool) void other.terminate()
        resolve(found)
      })
      w.on('error', reject)
    }
  })
  const hash = sha256d(Buffer.from(hex, 'hex')).reverse().toString('hex')
  const record = { height, hash, hex }
  makeSnapshot([parseProviderHeader(checkpoint, 'whatsonchain', checkpoint.height), record]) // Throws unless linkage and proof of work pass.
  mkdirSync(new URL('tests/fixtures/conflict/', root), { recursive: true })
  writeFileSync(
    new URL('tests/fixtures/conflict/mined-block.json', root),
    JSON.stringify(
      {
        note: 'Synthetic block at testnet minimum difficulty after the real checkpoint. Contains the conflict fixture issuance (offset 1) and branch A (offset 2). Generated by scripts/fixtures/mine-conflict-block.ts.',
        header: record,
        issuanceTxid,
        winnerTxid,
        issuancePath: issuancePath.toHex(),
        winnerPath: winnerPath.toHex(),
      },
      null,
      1,
    ) + '\n',
  )
  console.log(`Found ${hash} in ${Math.round((Date.now() - started) / 1000)} s`)
}
